class MapMyCellsConfig(BaseModel):
    """Configuration for local MapMyCells cell type assignment."""

    pair_id: str
    output_dir: Path
    samples: list[MapMyCellsSampleConfig]
    reference_mode: Literal["whole_brain", "region", "both"] = "both"
    reference_atlas: Literal["whb", "wmb"] = "whb"
    query_species: Literal["human", "mouse"] = "human"
    auto_download_references: bool = True
    marker_lookup_path: Path | None = None
    precomputed_stats_path: Path | None = None
    gene_mapping_db_path: Path | None = None
    region_name: str = "frontal_a44_a45_a46_a32_acc"
    region_labels: list[str] = Field(
        default_factory=lambda: [
            "Human A44-A45",
            "Human A46",
            "Human A32",
            "Human ACC",
        ]
    )
    region_cache_dir: Path = Path("./mapmycells_cache")
    region_min_cells_per_leaf: int = Field(default=10, ge=1)
    region_force_rebuild: bool = False
    region_query_markers_n_per_utility: int = Field(default=10, ge=1)
    drop_level: str | None = None
    normalization: Literal["raw", "log2CPM"] = "raw"
    bootstrap_factor: float = Field(default=0.9, gt=0.0, le=1.0)
    bootstrap_iteration: int = Field(default=100, ge=1)
    n_processors: int = Field(default=4, ge=1)
    chunk_size: int | None = Field(default=None, ge=1)
    rng_seed: int | None = None
    max_gb: float | None = Field(default=None, gt=0.0)
    tmp_dir: Path | None = None
    cloud_safe: bool = False
    flatten: bool = False
    verbose_csv: bool = False
    plots_only: bool = False
    extra_args: list[str] = Field(default_factory=list)

    @field_validator("region_labels", mode="before")
    @classmethod
    def _parse_region_labels(cls: type[MapMyCellsConfig], value: Any) -> list[str]:
        if value is None:
            return []
        if isinstance(value, str):
            raw = value.strip()
            if not raw:
                return []
            if raw.startswith("["):
                import json

                parsed = json.loads(raw)
                if not isinstance(parsed, list):
                    raise ValueError("region_labels JSON must decode to a list")
                value = parsed
            else:
                return [part.strip() for part in raw.split(",") if part.strip()]
        if isinstance(value, list | tuple | set):
            return [str(item).strip() for item in value if str(item).strip()]
        raise ValueError("region_labels must be a list or comma-separated string")

    @field_validator("region_name")
    @classmethod
    def _validate_region_name(cls: type[MapMyCellsConfig], value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("region_name must not be empty")
        return cleaned

    @model_validator(mode="after")
    def _validate_reference_inputs(self: MapMyCellsConfig) -> MapMyCellsConfig:
        if self.query_species == "mouse" and self.reference_atlas != "wmb":
            raise ValueError(
                "mouse MapMyCells queries currently require the WMB reference atlas"
            )
        if (
            not self.plots_only
            and self.reference_mode in {"whole_brain", "both"}
            and not self.auto_download_references
        ):
            if self.marker_lookup_path is None:
                raise ValueError(
                    "marker_lookup_path is required when automatic reference "
                    "downloads are disabled"
                )
            if self.precomputed_stats_path is None:
                raise ValueError(
                    "precomputed_stats_path is required when automatic reference "
                    "downloads are disabled"
                )
        if (
            not self.plots_only
            and self.reference_mode in {"region", "both"}
            and not self.region_labels
        ):
            raise ValueError(
                "region_labels must contain at least one Allen WHB ROI label when "
                "reference_mode includes region"
            )
        if (
            not self.plots_only
            and self.reference_atlas == "wmb"
            and self.query_species == "human"
            and self.gene_mapping_db_path is None
            and not self.auto_download_references
        ):
            raise ValueError(
                "gene_mapping_db_path is required for human-to-WMB mapping when "
                "automatic reference downloads are disabled"
            )
        if (
            not self.plots_only
            and self.reference_atlas == "wmb"
            and self.reference_mode in {"region", "both"}
            and any(label.lower().startswith("human ") for label in self.region_labels)
        ):
            raise ValueError(
                "WMB region_labels must be mouse region_of_interest_acronym values, "
                "not the default Human WHB labels"
            )
        if (
            self.reference_atlas == "wmb"
            and self.query_species == "human"
            and self.drop_level is None
        ):
            self.drop_level = "CCN20230722_SUPT"
        return self


class PipelineConfig(BaseSettings):
    """Top-level pipeline configuration, loadable from env vars."""

    output_root: Path = Path("./results")
    proseg_search_paths: list[Path] = [
        Path("/usr/bin/proseg"),
        Path("/usr/local/bin/proseg"),
    ]
    proseg_install_path: Path = Path("/usr/bin/proseg")
    proseg_auto_install: bool = True
    max_ram_gb: float = 600.0

    model_config = {"env_prefix": "MERXEN_"}


def load_config_from_json(path: Path, config_class: type[BaseModel]) -> BaseModel:
    """Load and validate a config from a JSON file.

    Args:
        path: Path to the JSON config file.
        config_class: The Pydantic model class to validate against.

    Returns:
        A validated config instance.
    """
    import json

    with open(path) as f:
        data = json.load(f)
    return config_class.model_validate(data)
