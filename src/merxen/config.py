"""Configuration dataclasses for the MerXen pipeline.

All pipeline parameters are defined here as Pydantic models. Configuration
is loaded from JSON files (generated by Nextflow) and validated at startup.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, Field, field_validator, model_validator
from pydantic_settings import BaseSettings


class CellposeConfig(BaseModel):
    """Parameters for Cellpose segmentation."""

    model_type: str = "cyto3"
    gpu: bool = True
    diameter: float | None = None
    flow_threshold: float = 0.8
    cellprob_threshold: float = -5.0
    tile_overlap: float = 0.15
    bsize: int = 256
    factor_rescale: float = 1.0
    use_bfloat16: bool = True

    @field_validator("factor_rescale")
    @classmethod
    def _validate_rescale(cls: type[CellposeConfig], v: float) -> float:
        if abs(v - 1.0) > 1e-12:
            msg = (
                "MerXen is configured for native-resolution tiled Cellpose only. "
                f"Got factor_rescale={v}. Must be 1.0."
            )
            raise ValueError(msg)
        return v


class MaskFilterConfig(BaseModel):
    """Parameters for post-segmentation mask filtering."""

    max_eccentricity: float = 0.99
    min_area_percentile: float = 1.0
    min_area_px: float | None = None
    final_min_area_um2: float | None = 5.0
    final_max_area_um2: float | None = 400.0
    final_filter_chunk_mb: int = 256
    n_jobs: int = 16
    show_progress: bool = True

    @field_validator("final_min_area_um2", "final_max_area_um2")
    @classmethod
    def _validate_optional_area(
        cls: type[MaskFilterConfig],
        v: float | None,
    ) -> float | None:
        if v is not None and v < 0:
            raise ValueError("area thresholds must be non-negative")
        return v

    @field_validator("final_filter_chunk_mb")
    @classmethod
    def _validate_filter_chunk_mb(cls: type[MaskFilterConfig], v: int) -> int:
        if int(v) <= 0:
            raise ValueError("final_filter_chunk_mb must be positive")
        return int(v)

    @model_validator(mode="after")
    def _validate_area_bounds(self: MaskFilterConfig) -> MaskFilterConfig:
        if (
            self.final_min_area_um2 is not None
            and self.final_max_area_um2 is not None
            and self.final_min_area_um2 > self.final_max_area_um2
        ):
            raise ValueError("final_min_area_um2 must be <= final_max_area_um2")
        return self


class TilingConfig(BaseModel):
    """Parameters for memory-adaptive Cellpose tiling."""

    model_config = {"populate_by_name": True}

    tile_size_candidates: list[int] = Field(
        default_factory=lambda: [6144, 4096, 3072, 2048]
    )
    stitch_overlap_px: int = Field(default=256, alias="tile_overlap")
    min_tile_size: int = 1024
    status_every_tiles: int = 10
    filter_per_tile: bool = True
    duplicate_iou_threshold: float = 0.25
    duplicate_overlap_fraction: float = 0.5
    min_remaining_fraction: float = 0.05
    edge_touch_policy: Literal["keep", "skip"] = "keep"
    write_stitching_stats: bool = True

    @field_validator("tile_size_candidates")
    @classmethod
    def _validate_tile_size_candidates(
        cls: type[TilingConfig], v: list[int]
    ) -> list[int]:
        values = [int(x) for x in v]
        if not values:
            raise ValueError("tile_size_candidates must not be empty")
        if any(x <= 0 for x in values):
            raise ValueError("tile_size_candidates values must be positive")
        return values

    @field_validator("stitch_overlap_px")
    @classmethod
    def _validate_stitch_overlap_px(cls: type[TilingConfig], v: int) -> int:
        if int(v) < 0:
            raise ValueError("stitch_overlap_px must be non-negative")
        return int(v)

    @field_validator("min_tile_size", "status_every_tiles")
    @classmethod
    def _validate_positive_int(cls: type[TilingConfig], v: int) -> int:
        if int(v) <= 0:
            raise ValueError("tiling integer parameters must be positive")
        return int(v)

    @field_validator(
        "duplicate_iou_threshold",
        "duplicate_overlap_fraction",
        "min_remaining_fraction",
    )
    @classmethod
    def _validate_fraction(cls: type[TilingConfig], v: float) -> float:
        value = float(v)
        if value < 0.0 or value > 1.0:
            raise ValueError("tiling fraction parameters must be between 0 and 1")
        return value

    @model_validator(mode="after")
    def _validate_core_size(self: TilingConfig) -> TilingConfig:
        valid_candidates = [
            x for x in self.tile_size_candidates if x >= int(self.min_tile_size)
        ]
        if not valid_candidates:
            raise ValueError(
                "tile_size_candidates must include at least one value >= min_tile_size"
            )
        for tile_size in valid_candidates:
            if int(tile_size) - (2 * int(self.stitch_overlap_px)) > 0:
                return self
        raise ValueError(
            "At least one tile_size_candidate must be larger than 2 * stitch_overlap_px"
        )


